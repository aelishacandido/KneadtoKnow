    private void initPosTab() {
        posTabPanel = new POSTabPanel();

        jPanel2.setLayout(new BorderLayout());
        jPanel2.removeAll();
        jPanel2.add(posTabPanel, BorderLayout.CENTER);
        jPanel2.revalidate();
        jPanel2.repaint();

        if (this.inventory != null) {
            posTabPanel.setInventory(this.inventory);
        }

        jTabbedPane1.addChangeListener(e -> {
            if (jTabbedPane1.getSelectedComponent() == jPanel2) {
                posTabPanel.refreshCatalogTable();
            }
        });
    }

